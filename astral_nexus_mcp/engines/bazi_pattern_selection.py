"""Six ordered legacy pattern gates on reconciled final strength and scores.

Source: geju_analysis/mingju.py::judge_mingju_type and its six analyzers.
This module only decides pattern entry and purity. Later useful-stem and
auspiciousness scoring belong to separate rules.
"""

from lunar_python.util import LunarUtil

from astral_nexus_mcp.engines.bazi_strength import RULES

VERSION = 'bazi-pattern-selection-3'
PRODUCER = {'木': '水', '火': '木', '土': '火', '金': '土', '水': '金'}
GENERATES = {'木': '火', '火': '土', '土': '金', '金': '水', '水': '木'}
KILLER = {'木': '金', '火': '水', '土': '木', '金': '火', '水': '土'}
DOMINANT_NAMES = {'木': '曲直格', '火': '炎上格', '土': '稼穑格',
                  '金': '从革格', '水': '润下格'}
ZHENGGE = {'正官': '正官格', '七杀': '七杀格', '正印': '正印格',
           '偏印': '偏印格', '正财': '正财格', '偏财': '偏财格',
           '食神': '食神格', '伤官': '伤官格'}
ORDER = ('transformation', 'dominant', 'follow_strong', 'follow_weak',
         'lu_ren', 'month_pattern')


def _main(pillar):
    return next(stem for stem, qi in RULES['branch_qi_type'][pillar['branch']].items()
                if qi == '本气')


def _breakers(pillars, day_element):
    """Old A/B/C structural break count for dominant and follow-strong."""
    killer = KILLER[day_element]
    rows = []
    for pillar in pillars:
        stem_element = LunarUtil.WU_XING_GAN[pillar['stem']]
        main_element = LunarUtil.WU_XING_GAN[_main(pillar)]
        if stem_element == killer:
            rows.append({'type': 'A', 'pillar': pillar['id'], 'stem': pillar['stem']})
        if main_element == killer:
            rows.append({'type': 'B', 'pillar': pillar['id'], 'stem': _main(pillar)})
        # The executable legacy C check uses its PRODUCER_OF map, which
        # points to the element generated by A. Preserve that exact gate.
        if stem_element == killer and GENERATES[killer] == main_element:
            rows.append({'type': 'C', 'pillar': pillar['id'], 'stem': _main(pillar)})
    return rows


def _month_pattern(pillars, totals):
    month = pillars[1]
    candidates = []
    for hidden in month['hidden_stems']:
        stem = hidden['stem']
        qi = RULES['branch_qi_type'][month['branch']][stem]
        element = LunarUtil.WU_XING_GAN[stem]
        visible = [p for p in pillars if p['id'] != 'day' and
                   p['stem_ten_god'] not in ('比肩', '劫财')]
        exact = next((p for p in visible if p['stem'] == stem and
                      p['stem_ten_god'] == hidden['ten_god']), None)
        same = next((p for p in visible
                     if LunarUtil.WU_XING_GAN[p['stem']] == element), None)
        match = exact or same
        if match:
            candidates.append({'stem': stem, 'qi': qi, 'element': element,
                               'ten_god': match['stem_ten_god'],
                               'pillar': match['id'],
                               'weight': {'本气': 3, '中气': 2, '余气': 1}[qi] +
                               (1.5 if exact else 1.)})
    if not candidates:
        stem = _main(month)
        candidates.append({'stem': stem, 'qi': '本气',
                           'element': LunarUtil.WU_XING_GAN[stem],
                           'ten_god': next(h['ten_god'] for h in month['hidden_stems']
                                           if h['stem'] == stem),
                           'pillar': None, 'weight': 3.})
    qi_set = {row['qi'] for row in candidates}
    if '本气' not in qi_set and {'中气', '余气'} <= qi_set:
        middle = max((row for row in candidates if row['qi'] == '中气'),
                     key=lambda row: row['weight'])
        residual = max((row for row in candidates if row['qi'] == '余气'),
                       key=lambda row: row['weight'])
        denominator = totals[middle['element']] + totals[residual['element']]
        if denominator <= 0:
            return {'status': 'not_covered', 'reason': '中余气五行分母非正。',
                    'candidates': candidates, 'selected': None}
        for row in candidates:
            if row['qi'] == '中气' and row['element'] == middle['element']:
                row['weight'] += totals[middle['element']] / denominator * .5
            elif row['qi'] == '余气' and row['element'] == residual['element']:
                row['weight'] += totals[residual['element']] / denominator * .5
    selected = max(candidates, key=lambda row: row['weight'])
    return {'status': 'matched' if selected['ten_god'] in ZHENGGE else 'no_pattern',
            'candidates': candidates,
            'selected': ZHENGGE.get(selected['ten_god']),
            'selected_evidence': selected}


def evaluate(pillars, branch, five_he, environment, strength, follow_weak):
    """Evaluate every entry gate, then branch only when a fake pattern matches."""
    final = strength.get('final_strength')
    if (not final or environment.get('status') != 'isolated_environment_stage' or
            branch.get('status') not in ('isolated_pair_stages', 'isolated_group_branch_stage')):
        return {'version': VERSION, 'status': 'not_covered', 'reason': '完整前序或旺衰未对账。',
                'layers': [], 'paths': []}
    totals = environment['totals_after']
    total = sum(totals.values())
    if total <= 0:
        return {'version': VERSION, 'status': 'not_covered', 'reason': '五行总分非正。',
                'layers': [], 'paths': []}
    day = pillars[2]['stem']
    day_element = LunarUtil.WU_XING_GAN[day]
    month_element = LunarUtil.WU_XING_GAN[_main(pillars[1])]
    level = final['level']
    day_score = next(row['score'] for row in environment['visible_balances_after']
                     if row['pillar'] == 'day')
    day_share = day_score / total * 100
    element_share = totals[day_element] / total * 100
    support_share = (totals[day_element] + totals[PRODUCER[day_element]]) / total * 100
    breakers = _breakers(pillars, day_element)
    layers = []

    day_pairs = [pair for pair in five_he.get('applied_pairs', []) if 'day' in pair]
    transformation = None
    if day_pairs:
        pair = day_pairs[0]
        candidate = next((row for row in five_he['candidates']
                          if row['pillars'] == pair), None)
        if candidate:
            target = candidate['target_element']
            target_share = totals[target] / total * 100
            combined = (totals[target] + totals[PRODUCER[target]]) / total * 100
            gates = {'extremely_weak': level == '极弱',
                     'day_is_converted': day_element != target,
                     'target_at_least_50': target_share >= 50,
                     'target_and_producer_at_least_80': combined >= 80}
            if all(gates.values()):
                partial = any(row['pillars'] == pair and row.get('grade') == '部分合化'
                              for row in five_he.get('applied_pair_details', []))
                if not five_he.get('applied_pair_details'):
                    return {'version': VERSION, 'status': 'not_covered',
                            'reason': '五合已生效但逐对等级缺失。', 'layers': [], 'paths': []}
                transformation = {'pattern': f'化{target}格',
                                  'purity': '假化气格' if partial else '真化气格',
                                  'evidence': {'gates': gates, 'pair': pair,
                                               'target_share': round(target_share, 6),
                                               'combined_share': round(combined, 6)}}
    layers.append({'id': 'transformation', 'status': 'matched' if transformation else 'excluded',
                   'result': transformation})

    group = next((row for kind in ('sanhui', 'sanhe', 'sanxing')
                  for row in branch.get('events', [])
                  if row['kind'] == kind and row['target_element'] == day_element), None)
    dominant_gates = {'extremely_strong': level == '极旺',
                      'matching_group_event': group is not None,
                      'day_element_at_least_80': element_share >= 80,
                      'break_strength_under_2': len(breakers) < 2}
    dominant = None
    if all(dominant_gates.values()):
        both = any(LunarUtil.WU_XING_GAN[p['stem']] == day_element and
                   p['stem'] != day for p in pillars)
        dominant = {'pattern': DOMINANT_NAMES[day_element],
                    'purity': '真专旺格' if not breakers and both else '假专旺格',
                    'evidence': {'gates': dominant_gates, 'breakers': breakers,
                                 'group': group['rule_key'], 'yin_yang_pair': both}}
    layers.append({'id': 'dominant', 'status': 'matched' if dominant else 'excluded',
                   'result': dominant, 'gates': dominant_gates})

    strong_gates = {'extremely_strong': level == '极旺',
                    'month_matches_day': month_element == day_element,
                    # User-approved 2026-10-03 rule supersedes the legacy
                    # executable >10 gate and its conflicting >40 docstring.
                    'day_stem_over_20': day_share > 20,
                    'support_over_80': support_share > 80,
                    'opposition_under_20': 100 - support_share < 20,
                    'break_strength_under_2': len(breakers) < 2}
    strong = None
    if all(strong_gates.values()):
        purity = ('真从旺格' if not breakers and support_share > 90 and
                  100 - support_share < 10 else '假从旺格' if len(breakers) == 1 else None)
        if purity:
            strong = {'pattern': '从旺格', 'purity': purity,
                      'evidence': {'gates': strong_gates, 'breakers': breakers,
                                   'day_stem_share': round(day_share, 6),
                                   'support_share': round(support_share, 6)}}
    layers.append({'id': 'follow_strong', 'status': 'matched' if strong else 'excluded',
                   'result': strong, 'gates': strong_gates})

    weak = None
    if follow_weak and follow_weak['status'] == 'stage_candidate':
        weak = {'pattern': follow_weak['pattern_if_confirmed'],
                'purity': follow_weak['purity_if_final'],
                'evidence': follow_weak}
    layers.append({'id': 'follow_weak', 'status': 'matched' if weak else 'excluded',
                   'result': weak})

    month_god = LunarUtil.SHI_SHEN[day + _main(pillars[1])]
    lu = ('建禄格' if month_god == '比肩' else
          '阳刃格' if month_god == '劫财' and day in '甲丙戊庚壬' else
          '劫财格' if month_god == '劫财' else None)
    lu_result = {'pattern': lu, 'purity': None,
                 'evidence': {'month_main_god': month_god}} if lu else None
    layers.append({'id': 'lu_ren', 'status': 'matched' if lu else 'excluded',
                   'result': lu_result})

    month = _month_pattern(pillars, totals)
    month_result = ({'pattern': month['selected'], 'purity': None,
                     'evidence': month} if month['selected'] else None)
    layers.append({'id': 'month_pattern', 'status': month['status'],
                   'result': month_result})

    paths = []
    rejected = []
    for index, layer in enumerate(layers):
        if layer['status'] == 'not_covered':
            return {'version': VERSION, 'status': 'not_covered',
                    'reason': '已到达取格层但该层关键分母或配置未覆盖。',
                    'strength_level': level, 'layers': layers, 'paths': paths,
                    'final_pattern': None}
        selected = layer['result']
        if selected is None:
            continue
        paths.append({'id': layer['id'], 'assumptions': rejected.copy(),
                      **selected, 'decision': 'conditional_only' if selected['purity']
                      and selected['purity'].startswith('假') else 'rule_matched'})
        if selected['purity'] and selected['purity'].startswith('假'):
            rejected.append(f"{selected['pattern']}假格不成立")
            continue
        for later in layers[index + 1:]:
            later['status'] = 'not_reached'
        break
    if not paths:
        return {'version': VERSION, 'status': 'no_pattern',
                'reason': '六层入口均未选出可核对格局，保留未定。',
                'strength_level': level, 'layers': layers, 'paths': [],
                'final_pattern': None}
    # The ordered gates always provide a default result. A fake-pattern
    # branch also exposes the later paths as user-selectable alternatives.
    has_alternatives = len(paths) > 1
    return {'version': VERSION, 'status': 'calculated_selection',
            'reason': '按旧六层入口顺序复算；假格否定后继续下一层。',
            'strength_level': level, 'layers': layers, 'paths': paths,
            'final_pattern': paths[0]['pattern'],
            'default_path_id': paths[0]['id'],
            'resolution': 'calculated_with_alternatives' if has_alternatives else 'calculated',
            'limitation': '按首条命中路径给出默认结果；可选择后续条件路径。层次、吉凶与岁运另行计算。'}
